/**
 * Emits the Prisma-like database client: the shared `client.ts` runtime
 * (copied from a typechecked template) and one `db.ts` per schema binding a
 * TableClient per table over the generated metadata and field decoders.
 */
import * as fs from 'fs';
import { toCamelCase, toPascalCase } from 'inflekt';
import * as path from 'path';

import { IrSchema, IrTable } from '../ir';
import { exportConst, generateCode, namedImport, t, withJsDoc } from './babel';
import { tableFileName } from './barrel';

const findTemplateFile = (templateName: string): string => {
  const templatePath = path.join(__dirname, 'templates', templateName);
  if (fs.existsSync(templatePath)) return templatePath;
  throw new Error(`Could not find template file: ${templateName}. Searched in: ${templatePath}`);
};

/** The shared runtime, copied verbatim with the template note replaced. */
export const emitClientRuntime = (): string => {
  const content = fs.readFileSync(findTemplateFile('client.ts'), 'utf8');
  return content.replace(
    / \* NOTE: This file is read at codegen time and written to output\.\n \* Any changes here will affect all generated clients\.\n \*\/\n/,
    ' * Generated by pg-codegen. DO NOT EDIT.\n */\n/* eslint-disable */\n'
  );
};

const typeImport = (names: string[], source: string): t.ImportDeclaration => {
  const declaration = namedImport(names, source);
  declaration.importKind = 'type';
  return declaration;
};

const modelKey = (table: IrTable): string => toCamelCase(table.name);

/** The per-schema `db.ts`: a `create<Schema>Db` factory of bound TableClients. */
export const emitSchemaDbModule = (schema: IrSchema): string => {
  const pascal = toPascalCase(schema.name);
  const dbTypeName = `${pascal}Db`;
  const optionsName = `${pascal}DbOptions`;
  const factoryName = `create${pascal}Db`;

  const statements: t.Statement[] = [
    namedImport(['TableClient'], '../client'),
    typeImport(['Queryable'], '../client')
  ];

  for (const table of schema.tables) {
    const appType = toPascalCase(table.name);
    const model = toCamelCase(table.name);
    const file = `./${tableFileName(table.name)}`;
    statements.push(typeImport([appType], file));
    statements.push(namedImport([`${model}Fields`, `${model}Table`], file));
  }

  const tableNameProps = schema.tables.map(table => {
    const prop = t.tsPropertySignature(
      t.identifier(modelKey(table)),
      t.tsTypeAnnotation(t.tsStringKeyword())
    );
    prop.optional = true;
    return prop;
  });

  const schemaProp = t.tsPropertySignature(
    t.identifier('schema'),
    t.tsTypeAnnotation(t.tsStringKeyword())
  );
  schemaProp.optional = true;
  const tablesProp = t.tsPropertySignature(
    t.identifier('tables'),
    t.tsTypeAnnotation(t.tsTypeLiteral(tableNameProps))
  );
  tablesProp.optional = true;

  statements.push(
    withJsDoc(
      t.exportNamedDeclaration(
        t.tsInterfaceDeclaration(
          t.identifier(optionsName),
          null,
          null,
          t.tsInterfaceBody([schemaProp, tablesProp])
        )
      ),
      'Runtime overrides for the physical schema and per-table names, for tables provisioned into per-tenant schemas.'
    )
  );

  const dbMembers: t.TSTypeElement[] = schema.tables.map(table =>
    t.tsPropertySignature(
      t.identifier(modelKey(table)),
      t.tsTypeAnnotation(
        t.tsTypeReference(
          t.identifier('TableClient'),
          t.tsTypeParameterInstantiation([t.tsTypeReference(t.identifier(toPascalCase(table.name)))])
        )
      )
    )
  );
  const withParam = t.identifier('db');
  withParam.typeAnnotation = t.tsTypeAnnotation(t.tsTypeReference(t.identifier('Queryable')));
  const withMember = t.tsMethodSignature(
    t.identifier('$with'),
    null,
    [withParam],
    t.tsTypeAnnotation(t.tsTypeReference(t.identifier(dbTypeName)))
  );
  t.addComment(
    withMember,
    'leading',
    "* Rebind every table client to another connection (e.g. a transaction's PoolClient). ",
    false
  );
  dbMembers.push(withMember);

  statements.push(
    t.exportNamedDeclaration(
      t.tsInterfaceDeclaration(t.identifier(dbTypeName), null, null, t.tsInterfaceBody(dbMembers))
    )
  );

  const clientProperties: t.ObjectProperty[] = schema.tables.map(table => {
    const model = toCamelCase(table.name);
    const spec = t.objectExpression([
      t.objectProperty(
        t.identifier('schema'),
        t.logicalExpression(
          '??',
          t.optionalMemberExpression(t.identifier('options'), t.identifier('schema'), false, true),
          t.memberExpression(t.identifier(`${model}Table`), t.identifier('schema'))
        )
      ),
      t.objectProperty(
        t.identifier('table'),
        t.logicalExpression(
          '??',
          t.optionalMemberExpression(
            t.optionalMemberExpression(t.identifier('options'), t.identifier('tables'), false, true),
            t.identifier(modelKey(table)),
            false,
            true
          ),
          t.memberExpression(t.identifier(`${model}Table`), t.identifier('name'))
        )
      ),
      t.objectProperty(
        t.identifier('columnByField'),
        t.memberExpression(t.identifier(`${model}Table`), t.identifier('columnByField'))
      ),
      t.objectProperty(t.identifier('fields'), t.identifier(`${model}Fields`))
    ]);
    const jsonFields = table.columns.filter(column => column.scalar === 'json');
    if (jsonFields.length > 0) {
      spec.properties.push(
        t.objectProperty(
          t.identifier('jsonFields'),
          t.arrayExpression(jsonFields.map(column => t.stringLiteral(column.propertyName)))
        )
      );
    }
    const client = t.newExpression(t.identifier('TableClient'), [spec, t.identifier('db')]);
    client.typeParameters = t.tsTypeParameterInstantiation([
      t.tsTypeReference(t.identifier(toPascalCase(table.name)))
    ]);
    return t.objectProperty(t.identifier(modelKey(table)), client);
  });

  const nextParam = t.identifier('next');
  nextParam.typeAnnotation = t.tsTypeAnnotation(t.tsTypeReference(t.identifier('Queryable')));
  clientProperties.push(
    t.objectProperty(
      t.identifier('$with'),
      t.arrowFunctionExpression(
        [nextParam],
        t.callExpression(t.identifier(factoryName), [t.identifier('next'), t.identifier('options')])
      )
    )
  );

  const dbParam = t.identifier('db');
  dbParam.typeAnnotation = t.tsTypeAnnotation(t.tsTypeReference(t.identifier('Queryable')));
  const optionsParam = t.assignmentPattern(
    (() => {
      const id = t.identifier('options');
      id.typeAnnotation = t.tsTypeAnnotation(t.tsTypeReference(t.identifier(optionsName)));
      return id;
    })(),
    t.objectExpression([])
  );
  const factory = t.arrowFunctionExpression(
    [dbParam, optionsParam],
    t.objectExpression(clientProperties)
  );
  factory.returnType = t.tsTypeAnnotation(t.tsTypeReference(t.identifier(dbTypeName)));

  statements.push(
    withJsDoc(
      exportConst(factoryName, factory),
      `One Prisma-like client per table over any pg Pool/Client, decoding rows into the generated ${pascal} application types.`
    )
  );

  return generateCode(statements);
};
