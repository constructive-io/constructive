/**
 * Write the generated Authz node reference page as Markdown, for the constructive-security skill. A copy that differs
 * from this output is stale. Dev-time only: the page is not part of the runtime exports.
 *
 * Usage:
 *   ts-node src/codegen/generate-reference.ts --outdir <constructive-skills>/.agents/skills/constructive-security/references
 */
import { mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';

import * as authz from '../authz';
import type { JSONSchema, NodeTypeDefinition } from '../types';

const GENERATED = '> Generated from `node-type-registry`. Do not edit this file by hand; regenerate it from the registry.';

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const code = (text: string): string => `\`${text}\``;
const anchor = (heading: string): string => heading.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-');

function typeOf(schema: JSONSchema): string {
  if (schema.format === 'authz-expression') return 'an Authz expression';
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' or ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' or ');
  const kinds = Array.isArray(schema.type) ? schema.type : [schema.type ?? 'any'];
  const items = schema.items && !Array.isArray(schema.items) ? schema.items : undefined;
  const named = kinds.map((kind) => (kind === 'array' ? `${items ? typeOf(items) : 'any'}[]` : kind)).join(' or ');
  return schema.format === 'column-ref' ? `${named} (a column${schema['x-column-scope'] === 'foreign' ? ' of the other table' : ''})` : named;
}

function parameters(node: NodeTypeDefinition): string[] {
  const properties = Object.entries(node.parameter_schema.properties ?? {}).filter(([, schema]) => !schema.readOnly);
  if (properties.length === 0) return ['No parameters.'];
  const required = new Set(node.parameter_schema.required ?? []);
  return [
    '| Parameter | Type | Default | Required | What it does |',
    '|---|---|---|---|---|',
    ...properties.map(
      ([name, schema]) =>
        `| ${code(name)} | ${cell(typeOf(schema))} | ${schema.default === undefined ? '' : cell(code(JSON.stringify(schema.default)))} | ` +
        `${required.has(name) ? 'yes' : ''} | ${cell(schema.description ?? '')} |`
    )
  ];
}

const keys = (names: string[]): string => names.map(code).join(' and ');

// The cross-key rules of a schema that name groups of keys: exactly one of them (oneOf), or at least one (anyOf).
function keyRules(schema: JSONSchema): string[] {
  const groups = (branches: JSONSchema[] | undefined) => (branches?.every((branch) => branch.required?.length) ? branches.map((branch) => keys(branch.required)) : undefined);
  const one = groups(schema.oneOf);
  const any = groups(schema.anyOf);
  return [
    ...(one ? [`Give exactly one of ${one.join(', or ')}.`] : []),
    ...(any ? [`Give ${any.join(', or ')}.`] : []),
    ...(schema.allOf ?? []).flatMap(keyRules)
  ];
}

const list = (title: string, items: string[] | undefined): string[] => (items?.length ? [`**${title}**`, '', ...items.map((item) => `- ${item}`), ''] : []);

function nodeSection(node: NodeTypeDefinition): string[] {
  const written = Object.entries(node.parameter_schema.properties ?? {}).filter(([, schema]) => schema.readOnly).map(([name]) => code(name));
  return [
    `## ${node.name}`,
    '',
    node.summary ?? node.description,
    '',
    '**Parameters**',
    '',
    ...parameters(node),
    '',
    ...list('Rules', keyRules(node.parameter_schema)),
    ...(written.length ? [`**Written by the backend:** ${written.join(', ')}. A rule you write leaves them out.`, ''] : []),
    ...list('Use when', node.use_when),
    ...list('Avoid when', node.avoid_when),
    ...list('Risks', node.risks)
  ];
}

const page = (lines: string[]): string => `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;

/** Every Authz node as a Markdown reference page, in name order. Pure: the same nodes give the same page. */
export function renderAuthzReferencePage(nodes: NodeTypeDefinition[] = Object.values(authz)): string {
  const sorted = [...nodes].sort((a, b) => a.name.localeCompare(b.name));
  return page([
    '# Authz node reference',
    '',
    GENERATED,
    '',
    'Every Authz node of the registry, in name order: who one policy lets in, its parameters, and when to use it. A key a ' +
      'node does not list is refused.',
    '',
    '| Node | Who gets access |',
    '|---|---|',
    ...sorted.map((node) => `| [${code(node.name)}](#${anchor(node.name)}) | ${cell(node.summary ?? node.description)} |`),
    '',
    ...sorted.flatMap(nodeSection)
  ]);
}

function main(): void {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--outdir');
  if (i === -1 || !argv[i + 1]) {
    throw new Error(
      'generate-reference: no output folder was given. Pass --outdir <folder>, for example the references folder of the constructive-security skill.'
    );
  }
  const outdir = argv[i + 1];
  mkdirSync(outdir, { recursive: true });
  const file = join(outdir, 'authz-node-reference.md');
  writeFileSync(file, renderAuthzReferencePage());
  // eslint-disable-next-line no-console
  console.log(`[node-type-registry] wrote ${file}`);
}

if (require.main === module) main();
