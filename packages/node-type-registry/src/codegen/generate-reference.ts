/**
 * Write the registry's reference pages as Markdown into the skills folder of a constructive-skills checkout: the Authz
 * node reference for the constructive-security skill, and the blueprint node reference for the constructive-blueprints
 * skill. A copy that differs from this output is stale; --check lists the stale pages and exits 1. Dev-time only: the
 * pages are not part of the runtime exports.
 *
 * Usage:
 *   ts-node src/codegen/generate-reference.ts [--check] --outdir <constructive-skills>/.agents/skills
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';

import * as authz from '../authz';
import { blueprintDefinitionJsonSchema } from '../blueprint-schema.generated';
import { allNodeTypes } from '../index';
import type { JSONSchema, NodeTypeDefinition } from '../types';

const GENERATED = '> Generated from `node-type-registry`. Do not edit this file by hand; regenerate it from the registry.';

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const code = (text: string): string => `\`${text}\``;
const anchor = (heading: string): string => heading.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-');

function typeOf(schema: JSONSchema): string {
  if (schema.format === 'authz-expression') return 'an Authz expression';
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' or ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' or ');
  const kinds = Array.isArray(schema.type) ? schema.type : [schema.type ?? 'any'];
  const items = schema.items && !Array.isArray(schema.items) ? schema.items : undefined;
  const named = kinds.map((kind) => (kind === 'array' ? `${items ? typeOf(items) : 'any'}[]` : kind)).join(' or ');
  return schema.format === 'column-ref' ? `${named} (a column${schema['x-column-scope'] === 'foreign' ? ' of the other table' : ''})` : named;
}

function parameters(node: NodeTypeDefinition, omit: ReadonlySet<string> = new Set(), required: ReadonlySet<string> = new Set(node.parameter_schema.required ?? [])): string[] {
  const properties = Object.entries(node.parameter_schema.properties ?? {}).filter(([name, schema]) => !schema.readOnly && !omit.has(name));
  if (properties.length === 0) return ['No parameters.'];
  return [
    '| Parameter | Type | Default | Required | What it does |',
    '|---|---|---|---|---|',
    ...properties.map(
      ([name, schema]) =>
        `| ${code(name)} | ${cell(typeOf(schema))} | ${schema.default === undefined ? '' : cell(code(JSON.stringify(schema.default)))} | ` +
        `${required.has(name) ? 'yes' : ''} | ${cell(schema.description ?? '')} |`
    )
  ];
}

const keys = (names: string[]): string => names.map(code).join(' and ');
const listed = (names: string[]): string => (names.length < 2 ? names.map(code).join('') : `${names.slice(0, -1).map(code).join(', ')} and ${code(names[names.length - 1])}`);

// The cross-key rules of a schema that name groups of keys: exactly one of them (oneOf), or at least one (anyOf).
function keyRules(schema: JSONSchema): string[] {
  const groups = (branches: JSONSchema[] | undefined) => (branches?.every((branch) => branch.required?.length) ? branches.map((branch) => keys(branch.required)) : undefined);
  const one = groups(schema.oneOf);
  const any = groups(schema.anyOf);
  return [
    ...(one ? [`Give exactly one of ${one.join(', or ')}.`] : []),
    ...(any ? [`Give ${any.join(', or ')}.`] : []),
    ...(schema.allOf ?? []).flatMap(keyRules)
  ];
}

const list = (title: string, items: string[] | undefined): string[] => (items?.length ? [`**${title}**`, '', ...items.map((item) => `- ${item}`), ''] : []);

function nodeSection(node: NodeTypeDefinition): string[] {
  const written = Object.entries(node.parameter_schema.properties ?? {}).filter(([, schema]) => schema.readOnly).map(([name]) => code(name));
  return [
    `## ${node.name}`,
    '',
    node.summary ?? node.description,
    '',
    '**Parameters**',
    '',
    ...parameters(node),
    '',
    ...list('Rules', keyRules(node.parameter_schema)),
    ...(written.length ? [`**Written by the backend:** ${written.join(', ')}. A rule you write leaves them out.`, ''] : []),
    ...list('Use when', node.use_when),
    ...list('Avoid when', node.avoid_when),
    ...list('Risks', node.risks)
  ];
}

const page = (lines: string[]): string => `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;

/** Every Authz node as a Markdown reference page, in name order. Pure: the same nodes give the same page. */
export function renderAuthzReferencePage(nodes: NodeTypeDefinition[] = Object.values(authz)): string {
  const sorted = [...nodes].sort((a, b) => a.name.localeCompare(b.name));
  return page([
    '# Authz node reference',
    '',
    GENERATED,
    '',
    'Every Authz node of the registry, in name order: who one policy lets in, its parameters, and when to use it. A key a ' +
      'node does not list is refused.',
    '',
    '| Node | Who gets access |',
    '|---|---|',
    ...sorted.map((node) => `| [${code(node.name)}](#${anchor(node.name)}) | ${cell(node.summary ?? node.description)} |`),
    '',
    ...sorted.flatMap(nodeSection)
  ]);
}

type Json = Record<string, any>;

const DEFS = (blueprintDefinitionJsonSchema as Json).$defs as Record<string, Json>;

/** The part of a `$type`-keyed blueprint schema for one node: what an entry of that type must give, if the schema takes it. */
const branchOf = (schema: Json, name: string): Json | undefined =>
  (schema.allOf as Json[] | undefined)?.find((part) => part.if?.properties?.$type?.const === name)?.then;

// The families in the order a person builds a table, then the entries beside tables. A new family comes last.
const FAMILIES = ['data', 'check', 'search', 'process', 'job', 'event', 'guard', 'limit', 'relation', 'view'];
const familyOf = (node: NodeTypeDefinition): string => node.category.split('_')[0];
const familyRank = (family: string): number => (FAMILIES.includes(family) ? FAMILIES.indexOf(family) : FAMILIES.length);

interface Placement {
  where: string;
  string: string;
  lines: string[];
  omit: Set<string>;
  required?: Set<string>;
  rules: string[];
}

// Where a blueprint names a node and what its entry must give, read from the blueprint JSON Schema, which the tools
// check blueprints with.
function placementOf(node: NodeTypeDefinition): Placement {
  const shorthand = (DEFS.BlueprintNodeShorthand.enum as string[]).includes(node.name);
  if (branchOf(DEFS.BlueprintNodeObject, node.name)) {
    const object = `\`{ "$type": "${node.name}", "data": { … } }\``;
    return {
      where: '`tables[].nodes`',
      string: shorthand ? 'yes' : 'no',
      lines: [`**In a blueprint:** in \`tables[].nodes\`, as ${shorthand ? `\`"${node.name}"\` or as ${object}.` : `${object}. \`data\` is required.`}`],
      omit: new Set(),
      rules: []
    };
  }
  const relation = branchOf(DEFS.BlueprintRelation, node.name);
  if (relation) {
    const required: string[] = relation.required ?? [];
    const set = (node.parameter_schema.required ?? []).filter((key) => !required.includes(key));
    const ends = (DEFS.BlueprintRelation.allOf as Json[]).filter((part) => !part.if);
    return {
      where: '`relations[]`',
      string: '',
      lines: [
        `**In a blueprint:** in \`relations[]\`, as \`{ "$type": "${node.name}", … }\` with the parameters at the top level. ` +
          `${required.length ? `Required: ${listed(required)}.` : 'Nothing is required beyond the two ends.'}` +
          `${set.length ? ` The backend sets ${listed(set)} from the two ends.` : ''}`
      ],
      omit: new Set(set),
      required: new Set(required),
      rules: keyRules({ allOf: ends })
    };
  }
  return { where: 'none', string: '', lines: ['**In a blueprint:** no key of a blueprint takes it.'], omit: new Set(), rules: [] };
}

function blueprintNodeSection(node: NodeTypeDefinition): string[] {
  const placement = placementOf(node);
  return [
    `### ${node.name}`,
    '',
    node.description,
    '',
    ...placement.lines,
    '',
    '**Parameters**',
    '',
    ...parameters(node, placement.omit, placement.required),
    '',
    ...list('Rules', [...placement.rules, ...keyRules(node.parameter_schema)])
  ];
}

/**
 * Every node that is not an Authz node as a Markdown reference page, by family and in name order: where a blueprint
 * names it, whether a table can name it as a string, and its parameters. Pure: the same nodes give the same page.
 */
export function renderBlueprintNodeReferencePage(nodes: NodeTypeDefinition[] = allNodeTypes): string {
  const sorted = nodes
    .filter((node) => node.category !== 'authz')
    .sort((a, b) => familyRank(familyOf(a)) - familyRank(familyOf(b)) || familyOf(a).localeCompare(familyOf(b)) || a.name.localeCompare(b.name));
  const families = [...new Set(sorted.map(familyOf))];
  const heading = (family: string) => `${family[0].toUpperCase()}${family.slice(1)} nodes`;
  return page([
    '# Blueprint node reference',
    '',
    GENERATED,
    '',
    'Every node of the registry except the Authz nodes, by family and in name order: where a blueprint names it, and its ' +
      'parameters. A table names a node in `nodes` as a string only when the node needs no data; otherwise it gives the ' +
      'object with `data`. The Authz nodes are in the Authz node reference of the constructive-security skill.',
    '',
    '| Node | In a blueprint | As a string |',
    '|---|---|---|',
    ...sorted.map((node) => {
      const placement = placementOf(node);
      return `| [${code(node.name)}](#${anchor(node.name)}) | ${placement.where} | ${placement.string} |`;
    }),
    '',
    ...families.flatMap((family) => [`## ${heading(family)}`, '', ...sorted.filter((node) => familyOf(node) === family).flatMap(blueprintNodeSection)])
  ]);
}

/** Each reference page this package renders, under its path in the skills folder of constructive-skills. */
export function referencePages(): Array<{ path: string; text: string }> {
  return [
    { path: 'constructive-security/references/authz-node-reference.md', text: renderAuthzReferencePage() },
    { path: 'constructive-blueprints/references/node-reference.md', text: renderBlueprintNodeReferencePage() }
  ];
}

/** The pages under `skillsDir` that are missing or differ from a fresh render. */
export function stalePages(skillsDir: string): string[] {
  return referencePages()
    .filter(({ path, text }) => !existsSync(join(skillsDir, path)) || readFileSync(join(skillsDir, path), 'utf8') !== text)
    .map(({ path }) => path);
}

function main(): void {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--outdir');
  if (i === -1 || !argv[i + 1]) {
    throw new Error(
      'generate-reference: no output folder was given. Pass --outdir <folder>: the .agents/skills folder of a constructive-skills checkout.'
    );
  }
  const skillsDir = argv[i + 1];
  if (argv.includes('--check')) {
    const stale = stalePages(skillsDir);
    // eslint-disable-next-line no-console
    for (const path of stale) console.log(`stale ${path}`);
    if (stale.length) {
      // eslint-disable-next-line no-console
      console.error(`\n${stale.length} reference page(s) differ from the registry. Run this again without --check, and commit the pages.`);
      process.exit(1);
    }
    // eslint-disable-next-line no-console
    console.log('[node-type-registry] the reference pages match the registry.');
    return;
  }
  for (const { path, text } of referencePages()) {
    mkdirSync(dirname(join(skillsDir, path)), { recursive: true });
    writeFileSync(join(skillsDir, path), text);
    // eslint-disable-next-line no-console
    console.log(`[node-type-registry] wrote ${join(skillsDir, path)}`);
  }
}

if (require.main === module) main();
