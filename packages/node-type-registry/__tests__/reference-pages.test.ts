import * as authz from '../src/authz';
import { renderAuthzReferencePage } from '../src/codegen/generate-reference';
import type { NodeTypeDefinition } from '../src/types';

const authzNodes: NodeTypeDefinition[] = Object.values(authz);

describe('reference pages', () => {
  test('the node reference has every Authz node, its words and its parameters', () => {
    const page = renderAuthzReferencePage();
    for (const node of authzNodes) {
      const section = page.slice(page.indexOf(`## ${node.name}\n`)).split('\n## ')[0];
      expect(section).toContain(node.summary);
      for (const [param, schema] of Object.entries(node.parameter_schema.properties ?? {})) {
        if (schema.readOnly) expect(section).toMatch(new RegExp(`\\*\\*Written by the backend:\\*\\*[^\\n]*\`${param}\``));
        else expect(section).toContain(`| \`${param}\` |`);
      }
      for (const text of [...(node.use_when ?? []), ...(node.avoid_when ?? []), ...(node.risks ?? [])]) expect(section).toContain(text);
    }
    expect(page).toContain('Give `membership_type`, or `entity_type`, or `sprt_schema` and `sprt_table`.');
  });

  test('the node reference says it is generated, and has no date or version in it', () => {
    const page = renderAuthzReferencePage();
    expect(page.split('\n')[2]).toBe('> Generated from `node-type-registry`. Do not edit this file by hand; regenerate it from the registry.');
    expect(page).not.toMatch(/\b\d{4}-\d{2}-\d{2}\b/);
    expect(page).not.toMatch(/\b\d+\.\d+\.\d+\b/);
    expect(page.endsWith('\n')).toBe(true);
  });

  test('the node reference is the same every time', () => {
    expect(renderAuthzReferencePage()).toBe(renderAuthzReferencePage());
  });

  test('the node reference is in name order, whatever order the nodes come in', () => {
    expect(renderAuthzReferencePage([...authzNodes].reverse())).toBe(renderAuthzReferencePage());
  });

  test('a changed node changes the page, so a stale copy shows', () => {
    const changed = authzNodes.map((node) => (node.name === 'AuthzMemberOwner' ? { ...node, risks: [...node.risks, 'A new risk.'] } : node));
    expect(renderAuthzReferencePage(changed)).not.toBe(renderAuthzReferencePage());
  });

  test('a table cell keeps a pipe as text', () => {
    const node = { ...authzNodes[0], parameter_schema: { type: 'object', properties: { mode: { type: 'string', description: 'a | b' } } } };
    expect(renderAuthzReferencePage([node])).toContain('a \\| b');
  });
});
