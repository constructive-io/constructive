import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { dirname, join } from 'path';

import * as authz from '../src/authz';
import { referencePages, renderAuthzReferencePage, renderBlueprintNodeReferencePage, stalePages } from '../src/codegen/generate-reference';
import { allNodeTypes } from '../src/index';
import type { NodeTypeDefinition } from '../src/types';

const authzNodes: NodeTypeDefinition[] = Object.values(authz);

describe('reference pages', () => {
  test('the node reference has every Authz node, its words and its parameters', () => {
    const page = renderAuthzReferencePage();
    for (const node of authzNodes) {
      const section = page.slice(page.indexOf(`## ${node.name}\n`)).split('\n## ')[0];
      expect(section).toContain(node.summary);
      for (const [param, schema] of Object.entries(node.parameter_schema.properties ?? {})) {
        if (schema.readOnly) expect(section).toMatch(new RegExp(`\\*\\*Written by the backend:\\*\\*[^\\n]*\`${param}\``));
        else expect(section).toContain(`| \`${param}\` |`);
      }
      for (const text of [...(node.use_when ?? []), ...(node.avoid_when ?? []), ...(node.risks ?? [])]) expect(section).toContain(text);
    }
    expect(page).toContain('Give `membership_type`, or `entity_type`, or `sprt_schema` and `sprt_table`.');
  });

  test('the node reference says it is generated, and has no date or version in it', () => {
    const page = renderAuthzReferencePage();
    expect(page.split('\n')[2]).toBe('> Generated from `node-type-registry`. Do not edit this file by hand; regenerate it from the registry.');
    expect(page).not.toMatch(/\b\d{4}-\d{2}-\d{2}\b/);
    expect(page).not.toMatch(/\b\d+\.\d+\.\d+\b/);
    expect(page.endsWith('\n')).toBe(true);
  });

  test('the node reference is the same every time', () => {
    expect(renderAuthzReferencePage()).toBe(renderAuthzReferencePage());
  });

  test('the node reference is in name order, whatever order the nodes come in', () => {
    expect(renderAuthzReferencePage([...authzNodes].reverse())).toBe(renderAuthzReferencePage());
  });

  test('a changed node changes the page, so a stale copy shows', () => {
    const changed = authzNodes.map((node) => (node.name === 'AuthzMemberOwner' ? { ...node, risks: [...node.risks, 'A new risk.'] } : node));
    expect(renderAuthzReferencePage(changed)).not.toBe(renderAuthzReferencePage());
  });

  test('a table cell keeps a pipe as text', () => {
    const node = { ...authzNodes[0], parameter_schema: { type: 'object', properties: { mode: { type: 'string', description: 'a | b' } } } };
    expect(renderAuthzReferencePage([node])).toContain('a \\| b');
  });
});

describe('the blueprint node reference', () => {
  const page = renderBlueprintNodeReferencePage();
  const section = (name: string) => page.slice(page.indexOf(`### ${name}\n`)).split('\n### ')[0].split('\n## ')[0];

  test('has every node but the Authz nodes, with its words and the parameters a blueprint gives', () => {
    for (const node of allNodeTypes) {
      if (node.category === 'authz') {
        expect(page).not.toContain(`### ${node.name}\n`);
        continue;
      }
      expect(section(node.name)).toContain(node.description);
    }
    expect(section('DataDirectOwner')).toContain('| `owner_field_name` |');
  });

  test('says where a blueprint names each node, and whether a table can name it as a string', () => {
    expect(section('DataId')).toContain('**In a blueprint:** in `tables[].nodes`, as `"DataId"` or as `{ "$type": "DataId", "data": { … } }`.');
    expect(section('JobTrigger')).toContain('**In a blueprint:** in `tables[].nodes`, as `{ "$type": "JobTrigger", "data": { … } }`. `data` is required.');
    expect(section('ViewAggregated')).toContain('**In a blueprint:** no key of a blueprint takes it.');
  });

  test('gives a relation the keys its blueprint entry needs, and leaves out the ids the backend sets', () => {
    const belongsTo = section('RelationBelongsTo');
    expect(belongsTo).toContain('Required: `delete_action`.');
    expect(belongsTo).toContain('The backend sets `source_table_id` and `target_table_id` from the two ends.');
    expect(belongsTo).toContain('Give exactly one of `source_table`, or `source_module`.');
    expect(belongsTo).not.toContain('| `source_table_id` |');
    expect(section('RelationSpatial')).toContain('Required: `name`, `operator`, `source_field` and `target_field`.');
  });

  test('is the same every time, in name order whatever order the nodes come in', () => {
    expect(renderBlueprintNodeReferencePage([...allNodeTypes].reverse())).toBe(page);
    expect(page.split('\n')[2]).toBe('> Generated from `node-type-registry`. Do not edit this file by hand; regenerate it from the registry.');
  });
});

describe('stalePages', () => {
  test('lists each page that is missing or differs from a fresh render, and nothing once they match', () => {
    const dir = mkdtempSync(join(tmpdir(), 'reference-pages-'));
    expect(stalePages(dir)).toEqual(referencePages().map(({ path }) => path));
    for (const { path, text } of referencePages()) {
      mkdirSync(dirname(join(dir, path)), { recursive: true });
      writeFileSync(join(dir, path), text);
    }
    expect(stalePages(dir)).toEqual([]);
    const [first] = referencePages();
    writeFileSync(join(dir, first.path), readFileSync(join(dir, first.path), 'utf8').replace('Authz', 'Auth'));
    expect(stalePages(dir)).toEqual([first.path]);
  });
});

