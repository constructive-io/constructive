import type { ExtensionFactory } from '@earendil-works/pi-coding-agent';

import { isBashEvent, isEditEvent, isWriteEvent } from './tool-call-helpers';

type Violation = { id: string; message: string };

const CODE_EXT_RE = /\.(?:ts|tsx|js|jsx|mjs|cjs)$/i;
const SQL_EXT_RE = /\.sql$/i;
const DEPLOY_SQL_RE = /(?:^|\/)packages\/[^/]+\/deploy\/[^/]+\.sql$/i;
const RENDERER_PATH_RE = /(?:^|\/)packages\/app\/src\/.+\.(?:tsx|ts|jsx|js)$/i;

const SKIP_MARKER_RE = /@generated\b|GENERATED FILE|AUTOGENERATED/i;
const TS_EXPECT_ERROR_RE = /@ts-expect-error\b/;

function checkTsAny(content: string, filePath: string): Violation | null {
  if (!CODE_EXT_RE.test(filePath)) return null;
  for (const line of content.split(/\r?\n/)) {
    if (TS_EXPECT_ERROR_RE.test(line)) continue;
    if (/\bas\s+any\b/.test(line)) {
      return {
        id: 'TS-001',
        message: '`as any` cast — type the value through the generated SDK instead',
      };
    }
  }
  return null;
}

function checkGraphqlLiteral(content: string, filePath: string): Violation | null {
  if (!CODE_EXT_RE.test(filePath)) return null;
  if (/\b(?:gql|graphql)\s*`/.test(content)) {
    return {
      id: 'CODEGEN-001',
      message: 'Raw GraphQL template literal — use generated hooks from `src/generated/`',
    };
  }
  if (/(["'`])\s*(?:query|mutation|subscription)\s+\w+\s*[({]/.test(content)) {
    return {
      id: 'CODEGEN-001',
      message: 'Inline GraphQL query string — use generated hooks from `src/generated/`',
    };
  }
  return null;
}

function checkBrowserDialog(content: string, filePath: string): Violation | null {
  if (!RENDERER_PATH_RE.test(filePath)) return null;
  if (/(?<![.\w])(?:window\.)?(?:alert|confirm|prompt)\s*\(/.test(content)) {
    return {
      id: 'UI-001',
      message:
        '`alert`/`confirm`/`prompt` in renderer code — use `AlertDialog` from `@/components/ui/alert-dialog`',
    };
  }
  return null;
}

function checkRawSchema(content: string, filePath: string): Violation | null {
  if (DEPLOY_SQL_RE.test(filePath)) return null;
  const isSqlFile = SQL_EXT_RE.test(filePath);
  const isCodeFile = CODE_EXT_RE.test(filePath);
  if (!isSqlFile && !isCodeFile) return null;
  if (/\b(?:CREATE\s+SCHEMA|ALTER\s+TABLE)\b/i.test(content)) {
    return {
      id: 'SCHEMA-001',
      message: 'Raw `CREATE SCHEMA` / `ALTER TABLE` outside `packages/*/deploy/*.sql`',
    };
  }
  return null;
}

const CHECKS = [checkTsAny, checkGraphqlLiteral, checkBrowserDialog, checkRawSchema];

function shouldSkipPath(filePath: string): boolean {
  if (filePath.includes('node_modules/')) return true;
  if (/(?:^|\/)src\/generated\//.test(filePath)) return true;
  if (/(?:^|\/)\.constructive\//.test(filePath)) return true;
  return false;
}

function inspect(filePath: string, content: string): Violation | null {
  if (shouldSkipPath(filePath)) return null;
  if (SKIP_MARKER_RE.test(content)) return null;
  for (const check of CHECKS) {
    const v = check(content, filePath);
    if (v) return v;
  }
  return null;
}

type HeredocWrite = { path: string; content: string };

function extractHeredocWrites(command: string): HeredocWrite[] {
  const out: HeredocWrite[] = [];
  const re =
    /\b(?:cat|tee)\s+(?:-a\s+)?(?:>>?\s*|--\s*)?["']?([^\s"'<>|;&]+)["']?\s*<<-?\s*['"]?(\w+)['"]?\s*\n([\s\S]*?)\n[ \t]*\2[ \t]*(?:\n|$)/g;
  let match: RegExpExecArray | null;
  while ((match = re.exec(command)) !== null) {
    out.push({ path: match[1], content: match[3] });
  }
  return out;
}

const RULE_DOC: Record<string, string> = {
  'TS-001': 'constructive-gotchas',
  'CODEGEN-001': 'constructive-gotchas',
  'UI-001': 'custom-tools',
  'SCHEMA-001': 'custom-tools',
};

function blockReason(v: Violation): { block: true; reason: string } {
  return {
    block: true,
    reason: `${v.id}: ${v.message} — see ${RULE_DOC[v.id] ?? 'custom-tools'}`,
  };
}

export const codeRules: ExtensionFactory = (pi) => {
  pi.on('tool_call', async (event) => {
    if (isEditEvent(event)) {
      const { path: filePath, edits } = event.input;
      for (const edit of edits) {
        const v = inspect(filePath, edit.newText);
        if (v) return blockReason(v);
      }
      return;
    }
    if (isWriteEvent(event)) {
      const v = inspect(event.input.path, event.input.content);
      if (v) return blockReason(v);
      return;
    }
    if (isBashEvent(event)) {
      for (const w of extractHeredocWrites(event.input.command)) {
        const v = inspect(w.path, w.content);
        if (v) return blockReason(v);
      }
      return;
    }
  });
};

export default codeRules;
