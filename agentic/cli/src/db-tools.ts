import * as fs from 'fs';
import * as path from 'path';

import { AgentCliConfig } from './config';

const EXTENSION_FILE = 'constructive-db-tools.js';

/**
 * Environment variables the generated extension reads at tool-call time.
 * Without CONSTRUCTIVE_ACCESS_TOKEN the tools load but report "not signed in".
 */
export const HOST_ENV_VARS = [
  'CONSTRUCTIVE_USER_ID',
  'CONSTRUCTIVE_ACCESS_TOKEN',
  'CONSTRUCTIVE_API_KEY',
  'CONSTRUCTIVE_API_ENDPOINT',
  'CONSTRUCTIVE_MODULES_ENDPOINT'
] as const;

// pi's TUI loads extensions from files under <agentDir>/extensions (via jiti),
// not from factories, so the db tools are wired by materializing a small
// generated entry there. The @agentic-kit/pi entry path is resolved from THIS
// package at assembly time and baked in, because node resolution from the
// appstash agent dir would not find it.
function extensionSource(pkgEntry: string): string {
  return `// Generated by @agentic-kit/cli — do not edit (rewritten on every \`agent\` run).
// Registers the Constructive typed db tools + confirm gate (@agentic-kit/pi)
// with credentials read from the environment on each call.
const { createDbTools } = require(${JSON.stringify(pkgEntry)});

module.exports = createDbTools({
  account: () => {
    const userId = process.env.CONSTRUCTIVE_USER_ID;
    const accessToken = process.env.CONSTRUCTIVE_ACCESS_TOKEN;
    if (!userId || !accessToken) return null;
    return { userId, accessToken, apiKey: process.env.CONSTRUCTIVE_API_KEY };
  },
  backendConfig: () => ({
    apiEndpoint: process.env.CONSTRUCTIVE_API_ENDPOINT,
    modulesEndpoint: process.env.CONSTRUCTIVE_MODULES_ENDPOINT
  })
});
`;
}

/**
 * Write the db-tools extension entry into pi's agent dir. Returns the file
 * path, or null when @agentic-kit/pi is not installed alongside the CLI.
 */
export function materializeDbTools(
  config: AgentCliConfig,
  log: (msg: string) => void
): string | null {
  let pkgEntry: string;
  try {
    pkgEntry = require.resolve('@agentic-kit/pi');
  } catch {
    log('db tools unavailable (@agentic-kit/pi not installed) — continuing without them');
    return null;
  }
  const dir = path.join(config.agentDir, 'extensions');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, EXTENSION_FILE);
  fs.writeFileSync(file, extensionSource(pkgEntry));
  return file;
}
