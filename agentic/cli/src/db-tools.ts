import * as fs from 'fs';
import * as path from 'path';

import { REPAIR_HINT } from './commands';
import { AgentCliConfig } from './config';

const EXTENSION_FILE = 'constructive-db-tools.js';

// pi's TUI loads extensions from files under <agentDir>/extensions (via jiti),
// not from factories, so the db tools are wired by materializing a small
// generated entry there. Both entry paths are resolved from THIS package at
// assembly time and baked in, because node resolution from the appstash agent
// dir would not find them.
function extensionSource(pkgEntry: string, sessionEntry: string): string {
  return `// Generated by @agentic-kit/cli — do not edit (rewritten on every \`agent\` run).
// Registers the Constructive typed db tools + confirm gate (@agentic-kit/pi)
// with credentials resolved on each call: CONSTRUCTIVE_* env vars first, then
// the shared session store (@agentic-kit/session).
const { createDbTools } = require(${JSON.stringify(pkgEntry)});
const { sessionToolsHost } = require(${JSON.stringify(sessionEntry)});

module.exports = createDbTools(
  sessionToolsHost({ signInHint: 'Run \`agent login\` to sign in.', repairHint: ${JSON.stringify(REPAIR_HINT)} }),
  { excludeTools: ['add_records', 'create_api_key'] }
);
`;
}

/**
 * Write the db-tools extension entry into pi's agent dir. Returns the file
 * path, or null when @agentic-kit/pi is not installed alongside the CLI.
 */
export function materializeDbTools(
  config: AgentCliConfig,
  log: (msg: string) => void
): string | null {
  let pkgEntry: string;
  try {
    pkgEntry = require.resolve('@agentic-kit/pi');
  } catch {
    log('db tools unavailable (@agentic-kit/pi not installed) — continuing without them');
    return null;
  }
  const sessionEntry = require.resolve('@agentic-kit/session');
  const dir = path.join(config.agentDir, 'extensions');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, EXTENSION_FILE);
  fs.writeFileSync(file, extensionSource(pkgEntry, sessionEntry));
  return file;
}
