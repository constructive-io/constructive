-- Capability fixture for schema-scoped dependency-closure introspection.
--
-- The integration test performs an explicit pg_available_extensions preflight
-- before executing this file. Keep extension creation unconditional: a missing
-- or partially installed capability must fail the fixture instead of silently
-- producing a smaller GraphQL schema.

BEGIN;

CREATE SCHEMA closure_ext;

CREATE EXTENSION ltree WITH SCHEMA closure_ext;
CREATE EXTENSION pg_textsearch WITH SCHEMA closure_ext;
CREATE EXTENSION pg_trgm WITH SCHEMA closure_ext;
CREATE EXTENSION postgis WITH SCHEMA closure_ext;
CREATE EXTENSION vector WITH SCHEMA closure_ext;

CREATE SCHEMA closure_api;
SET LOCAL search_path = closure_api, pg_catalog, closure_ext;

-- Exercise every user-defined pg_type.typtype that Graphile is expected to
-- retain, plus their generated array types. PostgreSQL 18 creates the
-- multirange type alongside the range type.
CREATE TYPE closure_api.closure_status AS ENUM ('ready', 'archived');

CREATE DOMAIN closure_api.closure_label AS text
  CHECK (VALUE <> '');

CREATE TYPE closure_api.closure_payload AS (
  label closure_api.closure_label,
  weight integer
);

CREATE TYPE closure_api.score_window AS RANGE (
  subtype = numeric,
  multirange_type_name = score_window_multirange
);

-- Exercise multirange input serialization independently from table output.
-- The runtime search_path omits closure_ext, so the signature and body remain
-- bound to the tenant schema through explicit identifiers.
CREATE FUNCTION closure_api.closure_multirange_probe(
  expected closure_api.score_window_multirange
)
RETURNS closure_api.score_window_multirange
LANGUAGE sql
IMMUTABLE
STRICT
SET search_path = pg_catalog, closure_api
AS $function$
  SELECT expected
$function$;

-- Timestamp codecs use Graphile's SQL cast path, so this probe covers the
