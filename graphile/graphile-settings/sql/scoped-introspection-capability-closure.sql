-- Defaults make this a root query field while its signature forces closure
-- traversal through enum, ltree, vector, and PostGIS types. The SQL body uses
-- fully qualified extension objects, so runtime search_path never needs the
-- shared extension schema.
CREATE FUNCTION closure_api.closure_function_probe(
  expected_status closure_api.closure_status DEFAULT 'ready',
  expected_path closure_ext.ltree DEFAULT 'customers.acme',
  expected_embedding closure_ext.vector(3) DEFAULT '[1,0,0]',
  expected_geom closure_ext.geometry DEFAULT
    closure_ext.st_setsrid(closure_ext.st_makepoint(-73.968, 40.785), 4326)
)
RETURNS SETOF closure_api.closure_records
LANGUAGE sql
STABLE
SET search_path = pg_catalog, closure_api
AS $function$
  SELECT record.*
  FROM closure_api.closure_records AS record
  WHERE record.status = expected_status
    AND record.path OPERATOR(closure_ext.<@) expected_path
    AND record.embedding OPERATOR(closure_ext.<=>) expected_embedding < 0.01
    AND closure_ext.st_intersects(record.geom, expected_geom)
$function$;

-- This schema deliberately has no type, function, operator-class, or index
-- dependency on pg_trgm/vector. Installed extensions are still a service-level
-- Graphile capability: @trgmSearch must behave identically under stock and
-- scoped introspection even when no retained object points at pg_trgm.
CREATE SCHEMA closure_plain_api;

CREATE TABLE closure_plain_api.plain_records (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  body text NOT NULL
);

COMMENT ON COLUMN closure_plain_api.plain_records.body IS E'@trgmSearch';

INSERT INTO closure_plain_api.plain_records (body)
VALUES ('tenant density capability without an extension-owned index');

